"""E. Verifiable Scientific Report & Publication Dashboard Generator.

Fundamental IINTS design principle:
Every single number, confidence interval, p-value, sample size, and protocol check
in ``SCIENTIFIC_REPORT.md`` is computed deterministically from stored experiment
artifacts — never generated by a language model.

Research, education and in-silico evaluation only; not a medical device.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, Optional, Union

import numpy as np
import pandas as pd

from iints.research.designer import ResearchPlan

__all__ = ["render_scientific_report_markdown", "plot_study_dashboard", "generate_verifiable_report_bundle"]


def _md_table(df: pd.DataFrame, float_fmt: str = "{:.2f}") -> str:
    if df.empty:
        return "_No records applicable for this section._"
    cols = list(df.columns)
    header = "| " + " | ".join(cols) + " |"
    sep = "| " + " | ".join(["---"] * len(cols)) + " |"
    lines = [header, sep]
    for _, row in df.iterrows():
        cells = []
        for c in cols:
            val = row[c]
            if isinstance(val, (float, np.floating)):
                if np.isnan(val):
                    cells.append("—")
                elif "p_" in c or "p_raw" in c:
                    cells.append(f"{val:.2e}" if val < 0.001 else f"{val:.4f}")
                else:
                    cells.append(float_fmt.format(val))
            else:
                cells.append(str(val))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_scientific_report_markdown(
    plan: ResearchPlan,
    analysis: Dict[str, Any],
    provenance: Dict[str, Any],
    *,
    planned_cells: int,
    completed_cells: int,
    failures_count: int,
    dashboard_rel_path: Optional[str] = None,
) -> str:
    """Build a complete, cryptographically traceable Markdown scientific report."""
    cond_df = analysis["condition_summary"]
    paired_df = analysis["paired_vs_control"]
    split_df = analysis["split_generalization"]
    ood_df = analysis["ood_boundary_summary"]
    cross_df = analysis["cross_simulator_summary"]
    worst_df = analysis["worst_cases"]

    deviations = []
    if completed_cells != planned_cells:
        deviations.append(f"Completed {completed_cells} of {planned_cells} planned simulation cells.")
    if failures_count > 0:
        deviations.append(f"{failures_count} cells raised execution errors (recorded in `failures.jsonl`).")
    deviation_text = (
        "None — 100% of pre-registered cells executed identically to the locked plan."
        if not deviations
        else " ".join(deviations)
    )

    hyps_md = "\n".join(
        f"- **{h.id}** (`{h.primary_endpoint}`, expected: `{h.direction}`): {h.statement}"
        for h in plan.hypotheses
    )
    controls_md = "\n".join(f"- {c}" for c in plan.confounders_and_controls)
    contract = plan.evaluation.missing_data_contract

    fig_block = f"\n![Study Dashboard]({dashboard_rel_path})\n" if dashboard_rel_path else ""

    sections = [
        f"# {plan.title}",
        f"> **Disclaimer**: {plan.disclaimer}",
        "",
        "## 1. Research Question & Pre-Registered Hypotheses",
        f"**Research Question:** {plan.research_question}",
        "",
        f"- **Plan ID:** `{plan.plan_id}` (`template={plan.template_id}`)",
        f"- **Pre-Registration Status:** `{plan.status}` by `{plan.approved_by}` at `{plan.approved_utc}`",
        f"- **Plan Lock SHA-256:** `{plan.plan_lock_sha256}`",
        "",
        "### Pre-Registered Hypotheses",
        hyps_md,
        "",
        "## 2. Methodology, Missing-Data Contract & Reproducibility",
        f"- **Virtual Profiles:** `{len(plan.patients)}` (`dev={sum(p.split == 'dev' for p in plan.patients)}`, "
        f"strictly held-out `unseen={sum(p.split == 'unseen' for p in plan.patients)}`)",
        f"- **Scenarios:** `{len(plan.scenarios)}` ({', '.join(f'`{s.id}` [{s.regime}]' for s in plan.scenarios)})",
        f"- **Sensor Conditions:** `{len(plan.sensor_conditions)}` (control: `{plan.control_condition_id}`)",
        f"- **Algorithms Evaluated:** {', '.join(f'`{a.model_id}`' for a in plan.algorithms)}",
        f"- **Primary Endpoint:** `{analysis['primary_metric'].upper()}` at `{analysis['primary_horizon_minutes']} min` "
        f"against `{contract.reference_target}`",
        f"- **Missing-Data Contract:** `allow_last_valid={contract.allow_last_valid_observation}`, "
        f"`expose_stale_flag={contract.expose_stale_flag_to_algorithm}`, "
        f"`expose_insulin_carbs={contract.expose_insulin_and_announced_carbs}`, "
        f"`impute={contract.impute_before_algorithm}`",
        f"- **Statistical Unit of Analysis:** `{plan.statistical_protocol.unit_of_analysis}` "
        f"(paired within-patient differences, `{plan.statistical_protocol.bootstrap_resamples}` bootstrap resamples, "
        f"Wilcoxon signed-rank + Holm-Bonferroni correction)",
        "",
        "### Methodological Controls",
        controls_md,
        fig_block,
        "## 3. Primary Cohort Results Across Sensor Conditions",
        _md_table(cond_df),
        "",
        "## 4. Within-Patient Paired Degradation vs Control",
        _md_table(paired_df),
        "",
        "## 5. Generalization to Strictly Held-Out Unseen Virtual Patients",
        _md_table(split_df[split_df["split"] == "unseen"] if "unseen" in set(split_df["split"]) else split_df),
        "",
        "## 6. Adversarial Out-of-Distribution (OOD) Boundary Scenarios",
        _md_table(ood_df),
    ]

    if not cross_df.empty:
        sections.extend(
            [
                "",
                "## 7. Cross-Simulator Validation",
                _md_table(cross_df),
            ]
        )

    sections.extend(
        [
            "",
            "## 8. Worst-Case Failure Audit (Top 10 Highest-Error Cells)",
            _md_table(worst_df),
            "",
            "## 9. Protocol Deviations & Limitations",
            f"- **Protocol Deviations:** {deviation_text}",
            "- **Pre-Clinical Scope Limitation:** All metrics are derived from mathematical virtual patients and "
            "parametric sensor fault models. Neither the bundled ODEs nor open-source adapters carry regulatory "
            "approval, and software benchmarks cannot substitute for clinical trials or human usability studies.",
            "",
            "## 10. Cryptographic Provenance & Software Environment",
            f"- **IINTS SDK Version:** `{provenance['sdk_version']}` (Git commit `{provenance['git']['commit']}`)",
            f"- **Python / Platform:** `{provenance['python_version']}` on `{provenance['platform']}`",
            f"- **Dependencies:** `{provenance['dependencies']}`",
            f"- **Config SHA-256:** `{provenance['config_sha256']}`",
            f"- **Artifact Hashes:** `{provenance['artifact_sha256']}`",
            "",
        ]
    )
    return "\n".join(sections)


def plot_study_dashboard(
    analysis: Dict[str, Any],
    output_path: Union[str, Path],
    *,
    title: str = "IINTS Research Lab — Benchmark Results",
) -> Optional[Path]:
    """Render a clean 4-panel white-background scientific summary figure."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        return None

    cond_df = analysis["condition_summary"]
    paired_df = analysis["paired_vs_control"]
    split_df = analysis["split_generalization"]
    ood_df = analysis["ood_boundary_summary"]

    fig, axes = plt.subplots(2, 2, figsize=(14, 9.5), dpi=160)
    fig.patch.set_facecolor("white")
    palette = ["#1b4965", "#ca6702", "#2a9d8f", "#ae2012", "#6c757d"]
    algos = list(dict.fromkeys(cond_df["algorithm_id"].tolist()))

    # Panel A: Mean MAE + 95% CI vs dropout condition
    ax = axes[0, 0]
    for i, algo in enumerate(algos):
        sub = cond_df[cond_df["algorithm_id"] == algo].sort_values("dropout_minutes")
        x = sub["dropout_minutes"].to_numpy(dtype=float)
        y = sub["mean_mae"].to_numpy(dtype=float)
        yerr_low = np.maximum(0.0, y - sub["ci95_low"].to_numpy(dtype=float))
        yerr_high = np.maximum(0.0, sub["ci95_high"].to_numpy(dtype=float) - y)
        ax.errorbar(
            x, y, yerr=[yerr_low, yerr_high], marker="o", linewidth=2.0, capsize=4,
            color=palette[i % len(palette)], label=algo,
        )
    ax.set_title("A. Overall 30-min MAE vs CGM Dropout (95% Patient CI)", fontweight="bold", fontsize=10.5)
    ax.set_xlabel("CGM Dropout Duration (minutes)")
    ax.set_ylabel("MAE vs True Blood Glucose (mg/dL)")
    ax.grid(True, alpha=0.25)
    ax.legend(frameon=True, fontsize=8.5)

    # Panel B: Paired within-patient Delta MAE vs 0-min control
    ax = axes[0, 1]
    if not paired_df.empty:
        for i, algo in enumerate(algos):
            sub = paired_df[paired_df["algorithm_id"] == algo].sort_values("dropout_minutes")
            if sub.empty:
                continue
            x = sub["dropout_minutes"].to_numpy(dtype=float)
            y = sub["mean_delta_mae"].to_numpy(dtype=float)
            lo = np.maximum(0.0, y - sub["ci95_delta_low"].to_numpy(dtype=float))
            hi = np.maximum(0.0, sub["ci95_delta_high"].to_numpy(dtype=float) - y)
            ax.errorbar(
                x, y, yerr=[lo, hi], marker="s", linewidth=2.0, capsize=4,
                color=palette[i % len(palette)], label=algo,
            )
    ax.axhline(0.0, color="#555555", linestyle="--", linewidth=1.0)
    ax.set_title("B. Paired Within-Patient Degradation (ΔMAE vs Control)", fontweight="bold", fontsize=10.5)
    ax.set_xlabel("CGM Dropout Duration (minutes)")
    ax.set_ylabel("Paired ΔMAE (mg/dL) — lower is more robust")
    ax.grid(True, alpha=0.25)

    # Panel C: Active-dropout MAE vs post-dropout recovery MAE at max dropout
    ax = axes[1, 0]
    max_drop = int(cond_df["dropout_minutes"].max())
    sub_max = (
        cond_df[cond_df["dropout_minutes"] == max_drop]
        .groupby("algorithm_id")[["mean_dropout_mae", "mean_recovery_mae"]]
        .mean()
        .reindex(algos)
    )
    xpos = np.arange(len(algos))
    w = 0.36
    ax.bar(xpos - w / 2, sub_max["mean_dropout_mae"].fillna(0.0), width=w, color="#ae2012", label=f"During {max_drop}m dropout")
    ax.bar(xpos + w / 2, sub_max["mean_recovery_mae"].fillna(0.0), width=w, color="#2a9d8f", label="Post-dropout recovery (30m)")
    ax.set_xticks(xpos)
    ax.set_xticklabels(algos, rotation=15, ha="right", fontsize=8.5)
    ax.set_title(f"C. Error During {max_drop}m Dropout vs Recovery Window", fontweight="bold", fontsize=10.5)
    ax.set_ylabel("MAE (mg/dL)")
    ax.grid(True, axis="y", alpha=0.25)
    ax.legend(frameon=True, fontsize=8.5)

    # Panel D: Generalization across Dev, Unseen Profiles, and OOD Stress at max dropout
    ax = axes[1, 1]
    dev_vals, unseen_vals, ood_vals = [], [], []
    for algo in algos:
        d_row = split_df[(split_df["split"] == "dev") & (split_df["dropout_minutes"] == max_drop) & (split_df["algorithm_id"] == algo)]
        u_row = split_df[(split_df["split"] == "unseen") & (split_df["dropout_minutes"] == max_drop) & (split_df["algorithm_id"] == algo)]
        dev_vals.append(float(d_row["mae"].mean()) if not d_row.empty else 0.0)
        unseen_vals.append(float(u_row["mae"].mean()) if not u_row.empty else 0.0)
        if not ood_df.empty:
            o_row = ood_df[(ood_df["dropout_minutes"] == max_drop) & (ood_df["algorithm_id"] == algo)]
            ood_vals.append(float(o_row["mae"].mean()) if not o_row.empty else 0.0)
        else:
            ood_vals.append(0.0)

    w3 = 0.26
    ax.bar(xpos - w3, dev_vals, width=w3, color="#1b4965", label="Dev profiles")
    ax.bar(xpos, unseen_vals, width=w3, color="#457b9d", label="Held-out Unseen profiles")
    if any(v > 0 for v in ood_vals):
        ax.bar(xpos + w3, ood_vals, width=w3, color="#ca6702", label="OOD Boundary scenarios")
    ax.set_xticks(xpos)
    ax.set_xticklabels(algos, rotation=15, ha="right", fontsize=8.5)
    ax.set_title(f"D. Generalization at {max_drop}m Dropout (Unseen & OOD)", fontweight="bold", fontsize=10.5)
    ax.set_ylabel("MAE (mg/dL)")
    ax.grid(True, axis="y", alpha=0.25)
    ax.legend(frameon=True, fontsize=8.5)

    fig.suptitle(f"{title}  [In-Silico Research Only]", fontweight="bold", fontsize=12.5, y=0.98)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    out_p = Path(output_path)
    out_p.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_p, facecolor="white")
    plt.close(fig)
    return out_p


def generate_verifiable_report_bundle(
    run_result: Dict[str, Any],
    analysis: Dict[str, Any],
) -> Dict[str, Path]:
    """Save statistical CSV tables, dashboard figure, and ``SCIENTIFIC_REPORT.md``."""
    out_root = Path(run_result["output_dir"])
    plan: ResearchPlan = run_result["plan"]

    cond_csv = out_root / "summary_by_condition.csv"
    paired_csv = out_root / "paired_degradation_vs_control.csv"
    unseen_csv = out_root / "generalization_by_split.csv"
    ood_csv = out_root / "ood_boundary_results.csv"

    analysis["condition_summary"].to_csv(cond_csv, index=False)
    analysis["paired_vs_control"].to_csv(paired_csv, index=False)
    analysis["split_generalization"].to_csv(unseen_csv, index=False)
    if not analysis["ood_boundary_summary"].empty:
        analysis["ood_boundary_summary"].to_csv(ood_csv, index=False)

    fig_path = plot_study_dashboard(analysis, out_root / "study_dashboard.png", title=plan.title)
    md = render_scientific_report_markdown(
        plan,
        analysis,
        run_result["provenance"],
        planned_cells=plan.total_simulation_cells(),
        completed_cells=int(run_result["resumed_cells"] + run_result["executed_cells"]),
        failures_count=len(run_result["failures"]),
        dashboard_rel_path=fig_path.name if fig_path is not None else None,
    )
    report_path = out_root / "SCIENTIFIC_REPORT.md"
    report_path.write_text(md, encoding="utf-8")

    out_paths = {
        "report_md": report_path,
        "condition_csv": cond_csv,
        "paired_csv": paired_csv,
        "unseen_csv": unseen_csv,
    }
    if fig_path is not None:
        out_paths["dashboard_png"] = fig_path
    return out_paths
