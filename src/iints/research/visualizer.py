def apply_scientific_plot_style() -> None:
    """Apply a restrained, publication-oriented matplotlib style."""

    plt.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": ["DejaVu Sans", "Helvetica Neue", "Arial"],
            "axes.edgecolor": "#64748B",
            "axes.linewidth": 0.9,
            "axes.titlesize": 12,
            "axes.titleweight": "bold",
            "axes.labelsize": 10,
            "axes.labelcolor": "#1E293B",
            "xtick.labelsize": 8.5,
            "ytick.labelsize": 8.5,
            "xtick.color": "#475569",
            "ytick.color": "#475569",
            "grid.color": "#CBD5E1",
            "grid.linestyle": "--",
            "grid.linewidth": 0.7,
            "legend.fontsize": 8.5,
            "legend.framealpha": 0.95,
            "figure.facecolor": "#FFFFFF",
        }
    )


def _optional_path(path: Path | None) -> str | None:
    return str(path) if path is not None else None


@dataclass(frozen=True)
class ScientificVisualizationArtifacts:
    """Files generated by the evidence-aware visualization suite."""

    output_dir: Path
    arena_radar_png: Path | None
    confounder_cosine_png: Path | None
    glucofm_decomposition_png: Path
    cgmacros_dualsensor_png: Path | None
    fda_safety_timeline_png: Path | None
    interactive_dashboard_html: Path

    def to_dict(self) -> dict[str, Any]:
        return {
            "output_dir": str(self.output_dir),
            "arena_radar_png": _optional_path(self.arena_radar_png),
            "confounder_cosine_png": _optional_path(self.confounder_cosine_png),
            "glucofm_decomposition_png": str(self.glucofm_decomposition_png),
            "cgmacros_dualsensor_png": _optional_path(self.cgmacros_dualsensor_png),
            "fda_safety_timeline_png": _optional_path(self.fda_safety_timeline_png),
            "interactive_dashboard_html": str(self.interactive_dashboard_html),
        }


def _resolve_output(output_path: Path | str) -> Path:
    output = Path(output_path).expanduser().resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    return output


def _read_evidence_table(path: Path | str) -> tuple[pd.DataFrame, Path, str]:
    source = Path(path).expanduser().resolve()
    if not source.is_file():
        raise FileNotFoundError(f"evidence table not found: {source}")
    if source.suffix.lower() in {".parquet", ".pq"}:
        frame = pd.read_parquet(source)
    elif source.suffix.lower() in {".tsv", ".txt"}:
        frame = pd.read_csv(source, sep="\t")
    else:
        frame = pd.read_csv(source)
    if frame.empty:
        raise ValueError(f"evidence table is empty: {source}")
    return frame, source, sha256(source.read_bytes()).hexdigest()


def _require_columns(frame: pd.DataFrame, columns: Sequence[str], label: str) -> None:
    missing = [column for column in columns if column not in frame.columns]
    if missing:
        raise ValueError(f"{label} evidence is missing required columns: {missing}")


def _finish_figure(fig: plt.Figure, output: Path) -> Path:
    fig.savefig(output, dpi=300, bbox_inches="tight")
    plt.close(fig)
    return output


def plot_foundation_arena_radar(
    output_path: Path | str,
    evaluation_artifacts: Sequence[Path | str] | None = None,
) -> Path:
    """Plot within-benchmark normalized scores from real arena artifacts.

    The radial values are min-max normalized only across the supplied models.
    They are not absolute performance percentages and must not be interpreted
    as clinical superiority.
    """

    artifacts = list(evaluation_artifacts or [])
    if len(artifacts) < 2:
        raise ValueError(
            "foundation radar requires at least two measured evaluation artifacts"
        )
    output = _resolve_output(output_path)
    report = run_foundation_model_arena(
        output_dir=output.parent / "foundation_arena_evidence",
        evaluation_artifacts=artifacts,
    )
    models = list(report.models)
    metric_names = sorted(set.intersection(*(set(model.metrics) for model in models)))
    if len(metric_names) < 3:
        raise ValueError("foundation radar requires at least three shared metrics")

    raw = np.array(
        [[model.metrics[name].value for name in metric_names] for model in models],
        dtype=float,
    )
    if not np.isfinite(raw).all():
        raise ValueError("foundation arena metrics must be finite")
    normalized = np.empty_like(raw)
    for column, name in enumerate(metric_names):
        values = raw[:, column]
        span = float(np.ptp(values))
        if span == 0.0:
            normalized[:, column] = 50.0
        else:
            scaled = 100.0 * (values - values.min()) / span
            if models[0].metrics[name].direction == "lower":
                scaled = 100.0 - scaled
            normalized[:, column] = scaled

    apply_scientific_plot_style()
    count = len(metric_names)
    angles = np.linspace(0.0, 2.0 * np.pi, count, endpoint=False).tolist()
    closed_angles = angles + angles[:1]
    fig, raw_ax = plt.subplots(
        figsize=(9.2, 8.2), subplot_kw={"polar": True}, dpi=300
    )
    ax = cast(PolarAxes, raw_ax)
    ax.set_ylim(0, 100)
    ax.set_yticks([25, 50, 75, 100])
    ax.set_yticklabels(["25", "50", "75", "100"])
    ax.set_xticks(angles)
    ax.set_xticklabels([name.replace("_", " ") for name in metric_names])
    palette = plt.get_cmap("tab10")
    for index, model in enumerate(models):
        values = normalized[index].tolist()
        closed = values + values[:1]
        color = palette(index % 10)
        ax.plot(closed_angles, closed, linewidth=2.0, label=model.model_name, color=color)
        ax.fill(closed_angles, closed, alpha=0.08, color=color)
    ax.set_title(
        "Foundation-model benchmark\n"
        "Within-benchmark min-max normalization (descriptive only)",
        pad=24,
    )
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.10), ncol=2)
    fig.text(
        0.5,
        0.015,
        f"Benchmark: {report.benchmark_id} | group-disjoint evidence | "
        "radial scores are relative, not clinical percentages",
        ha="center",
        fontsize=8,
        color="#475569",
    )
    return _finish_figure(fig, output)


def plot_confounder_cosine_analysis(
    output_path: Path | str,
    evidence_path: Path | str | None = None,
) -> Path:
    """Plot measured confounder-pair embeddings from a long-format table."""

    if evidence_path is None:
        raise ValueError("confounder plot requires an evidence CSV or Parquet file")
    frame, source, source_hash = _read_evidence_table(evidence_path)
    required = ["model_name", "si_ratio", "embedding_cosine_similarity"]
    _require_columns(frame, required, "confounder")
    clean = frame[required].copy()
    clean["model_name"] = clean["model_name"].astype(str)
    clean["si_ratio"] = pd.to_numeric(clean["si_ratio"], errors="coerce")
    clean["embedding_cosine_similarity"] = pd.to_numeric(
        clean["embedding_cosine_similarity"], errors="coerce"
    )
    clean = clean.dropna()
    if clean.empty:
        raise ValueError("confounder evidence contains no complete numeric rows")
    if (clean["si_ratio"] <= 0).any():
        raise ValueError("si_ratio must be positive")
    if not clean["embedding_cosine_similarity"].between(-1.0, 1.0).all():
        raise ValueError("embedding cosine similarity must lie in [-1, 1]")

    grouped = clean.groupby("model_name", sort=True)["embedding_cosine_similarity"]
    means = grouped.mean()
    standard_deviation = grouped.std().fillna(0.0)
    counts = grouped.size()
    apply_scientific_plot_style()
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 5.2), dpi=300)
    x = np.arange(len(means))
    colors = [plt.get_cmap("tab10")(index % 10) for index in range(len(means))]
    ax1.bar(x, means.to_numpy(), yerr=standard_deviation.to_numpy(), color=colors, capsize=4)
    ax1.set_xticks(x)
    ax1.set_xticklabels(
        [f"{name}\n(n={int(counts[name])})" for name in means.index], rotation=15, ha="right"
    )
    ax1.set_ylabel("Embedding cosine similarity")
    ax1.set_ylim(-1.05, 1.05)
    ax1.set_title("Measured similarity across physiological pairs")
    ax1.grid(axis="y")

    for index, model_name in enumerate(means.index):
        subset = clean[clean["model_name"] == model_name]
        ax2.scatter(
            subset["si_ratio"],
            subset["embedding_cosine_similarity"],
            label=model_name,
            alpha=0.75,
            color=colors[index],
            s=32,
        )
    ax2.set_xlabel("True insulin-sensitivity ratio used by the benchmark")
    ax2.set_ylabel("Embedding cosine similarity")
    ax2.set_ylim(-1.05, 1.05)
    ax2.set_title("Pair-level evidence")
    ax2.grid(True)
    ax2.legend()
    fig.suptitle("Physiological confounder benchmark (simulation evidence)")
    fig.text(
        0.5,
        0.01,
        f"Source: {source.name} | SHA-256 {source_hash[:16]}... | no synthetic fallback",
        ha="center",
        fontsize=8,
        color="#475569",
    )
    fig.tight_layout(rect=(0, 0.04, 1, 0.96))
    return _finish_figure(fig, _resolve_output(output_path))


def _architecture_box(
    ax: Axes,
    x: float,
    y: float,
    width: float,
    height: float,
    title: str,
    detail: str,
    color: str,
) -> None:
    patch = FancyBboxPatch(
        (x, y),
        width,
        height,
        boxstyle="round,pad=0.012,rounding_size=0.015",
        facecolor="#FFFFFF",
        edgecolor=color,
        linewidth=1.5,
    )
    ax.add_patch(patch)
    ax.text(x + width / 2, y + height * 0.65, title, ha="center", va="center", weight="bold", fontsize=9.5, color="#0F172A")
    ax.text(x + width / 2, y + height * 0.30, detail, ha="center", va="center", fontsize=7.8, color="#475569", linespacing=1.25)


def _arrow(ax: Axes, start: tuple[float, float], end: tuple[float, float]) -> None:
    ax.add_patch(
        FancyArrowPatch(start, end, arrowstyle="-|>", mutation_scale=12, linewidth=1.2, color="#64748B")
    )


