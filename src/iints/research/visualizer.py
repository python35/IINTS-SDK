def plot_cgmacros_dualsensor_comparison(
    output_path: Path | str,
    evidence_path: Path | str | None = None,
) -> Path:
    """Plot paired Dexcom/Libre measurements from an explicit evidence table."""

    if evidence_path is None:
        raise ValueError("dual-sensor plot requires a paired evidence table")
    frame, source, source_hash = _read_evidence_table(evidence_path)
    required = ["timestamp", "dexcom_mgdl", "libre_mgdl", "cohort"]
    _require_columns(frame, required, "dual-sensor")
    clean = frame[required].copy()
    clean["timestamp"] = pd.to_datetime(clean["timestamp"], errors="coerce")
    clean["dexcom_mgdl"] = pd.to_numeric(clean["dexcom_mgdl"], errors="coerce")
    clean["libre_mgdl"] = pd.to_numeric(clean["libre_mgdl"], errors="coerce")
    clean = clean.dropna()
    if clean.empty:
        raise ValueError("dual-sensor evidence contains no complete paired rows")
    clean["minute_of_day"] = clean["timestamp"].dt.hour * 60 + clean["timestamp"].dt.minute
    cohorts = sorted(clean["cohort"].astype(str).unique())
    fig, axes_raw = plt.subplots(1, len(cohorts), figsize=(5.2 * len(cohorts), 4.8), squeeze=False, dpi=300)
    axes = axes_raw[0]
    apply_scientific_plot_style()
    for ax, cohort in zip(axes, cohorts):
        subset = clean[clean["cohort"].astype(str) == cohort]
        aggregate = subset.groupby("minute_of_day")[["dexcom_mgdl", "libre_mgdl"]].median().sort_index()
        hours = aggregate.index.to_numpy(dtype=float) / 60.0
        ax.plot(hours, aggregate["dexcom_mgdl"], label="Dexcom median", color="#2563EB")
        ax.plot(hours, aggregate["libre_mgdl"], label="Libre median", color="#C2410C")
        mean_absolute_delta = float(np.mean(np.abs(subset["dexcom_mgdl"] - subset["libre_mgdl"])))
        ax.set_title(f"{cohort}\npaired rows n={len(subset):,}; mean |delta|={mean_absolute_delta:.1f} mg/dL")
        ax.set_xlabel("Time of day (h)")
        ax.set_ylabel("Glucose (mg/dL)")
        ax.grid(True)
        ax.legend()
    fig.suptitle("Paired dual-sensor evidence (descriptive medians)")
    fig.text(0.5, 0.01, f"Source: {source.name} | SHA-256 {source_hash[:16]}...", ha="center", fontsize=8, color="#475569")
    fig.tight_layout(rect=(0, 0.04, 1, 0.94))
    return _finish_figure(fig, _resolve_output(output_path))


def plot_fda_safety_mitigation_timeline(
    output_path: Path | str,
    evidence_path: Path | str | None = None,
) -> Path:
    """Plot a measured in-silico safety benchmark trace.

    Despite the legacy function name, this figure does not claim that a
    simulator trace is FDA validation or a reproduced adverse event.
    """

    if evidence_path is None:
        raise ValueError("safety timeline requires an in-silico benchmark trace")
    frame, source, source_hash = _read_evidence_table(evidence_path)
    required = ["time_minutes", "unsupervised_glucose_mgdl", "supervised_glucose_mgdl"]
    _require_columns(frame, required, "safety timeline")
    clean = frame[required].apply(pd.to_numeric, errors="coerce").dropna().sort_values("time_minutes")
    if len(clean) < 2:
        raise ValueError("safety timeline requires at least two complete rows")
    apply_scientific_plot_style()
    fig, ax = plt.subplots(figsize=(10.5, 5.2), dpi=300)
    ax.axhspan(0, 54, color="#FEE2E2", alpha=0.65, label="Very low glucose band (<54 mg/dL)")
    ax.axhspan(70, 180, color="#DCFCE7", alpha=0.45, label="Target range (70-180 mg/dL)")
    ax.plot(clean["time_minutes"], clean["unsupervised_glucose_mgdl"], color="#B91C1C", label="Comparator trace")
    ax.plot(clean["time_minutes"], clean["supervised_glucose_mgdl"], color="#047857", label="Supervisor trace")
    ax.set_xlabel("Simulation time (minutes)")
    ax.set_ylabel("Simulated glucose (mg/dL)")
    ax.set_title("Deterministic safety benchmark - in silico trace")
    ax.grid(True)
    ax.legend()
    fig.text(
        0.5,
        0.01,
        f"Source: {source.name} | SHA-256 {source_hash[:16]}... | not clinical or FDA validation",
        ha="center",
        fontsize=8,
        color="#475569",
    )
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    return _finish_figure(fig, _resolve_output(output_path))


def _dashboard_card(title: str, description: str, path: Path | None) -> str:
    if path is None:
        return (
            '<section class="card card--missing"><h2>'
            + escape(title)
            + "</h2><p>Not generated: no evidence artifact was supplied.</p></section>"
        )
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return (
        '<section class="card"><h2>'
        + escape(title)
        + '</h2><img alt="'
        + escape(title)
        + '" src="data:image/png;base64,'
        + encoded
        + '"><p>'
        + escape(description)
        + "</p></section>"
    )


def generate_interactive_dashboard_html(
    output_path: Path | str,
    radar_img_path: Path | None,
    confounder_img_path: Path | None,
    glucofm_img_path: Path,
    cgmacros_img_path: Path | None,
    fda_img_path: Path | None,
) -> Path:
    """Generate a standalone dashboard that distinguishes methods from evidence."""

    output = _resolve_output(output_path)
    cards = [
        _dashboard_card("GlucoFM reproduction architecture", "Implemented method schematic; not an experimental result.", glucofm_img_path),
        _dashboard_card("Foundation-model comparison", "Measured models evaluated under one group-disjoint benchmark contract.", radar_img_path),
        _dashboard_card("Physiological confounder analysis", "Pair-level simulation evidence loaded from a traceable table.", confounder_img_path),
        _dashboard_card("Paired dual-sensor analysis", "Descriptive statistics computed from supplied paired measurements.", cgmacros_img_path),
        _dashboard_card("Safety benchmark trace", "In-silico comparison; not clinical or regulatory validation.", fda_img_path),
    ]
    output.write_text(
        """<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>IINTS-AF evidence figures</title><style>body{font:15px/1.5 Georgia,serif;margin:0;background:#f8fafc;color:#0f172a}main{max-width:1200px;margin:auto;padding:28px}header{border-bottom:3px solid #334155;margin-bottom:22px}h1{font-size:27px}.notice{background:#fff7ed;border:1px solid #fdba74;padding:12px}.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(420px,1fr));gap:18px}.card{background:white;border:1px solid #cbd5e1;padding:16px}.card--missing{background:#f1f5f9;color:#475569}.card h2{font-size:18px;margin-top:0}.card img{width:100%;height:auto;border:1px solid #e2e8f0}</style></head><body><main><header><h1>IINTS-AF Scientific Visualization Suite</h1><p>Method diagrams and evidence-backed result figures are kept separate.</p></header><p class="notice">Missing evidence is shown as missing. The dashboard never replaces it with synthetic scores.</p><div class="grid">"""
        + "".join(cards)
        + "</div></main></body></html>",
        encoding="utf-8",
    )
    return output


def generate_all_scientific_visualizations(
    output_dir: Path | str = "results/scientific_visualizations",
    *,
    arena_evaluation_artifacts: Sequence[Path | str] | None = None,
    confounder_evidence: Path | str | None = None,
    cgmacros_evidence: Path | str | None = None,
    safety_trace: Path | str | None = None,
) -> ScientificVisualizationArtifacts:
    """Generate a method schematic plus only those figures backed by inputs."""

    output = Path(output_dir).expanduser().resolve()
    figure_dir = output / "figures"
    figure_dir.mkdir(parents=True, exist_ok=True)
    glucofm = plot_glucofm_dual_stream_decomposition(
        figure_dir / "glucofm_method_schematic.png"
    )
    arena = (
        plot_foundation_arena_radar(
            figure_dir / "foundation_arena_radar.png", arena_evaluation_artifacts
        )
        if arena_evaluation_artifacts
        else None
    )
    confounder = (
        plot_confounder_cosine_analysis(
            figure_dir / "confounder_cosine_analysis.png", confounder_evidence
        )
        if confounder_evidence is not None
        else None
    )
    dual_sensor = (
        plot_cgmacros_dualsensor_comparison(
            figure_dir / "paired_dual_sensor.png", cgmacros_evidence
        )
        if cgmacros_evidence is not None
        else None
    )
    safety = (
        plot_fda_safety_mitigation_timeline(
            figure_dir / "safety_benchmark_trace.png", safety_trace
        )
        if safety_trace is not None
        else None
    )
    dashboard = generate_interactive_dashboard_html(
        output / "index.html", arena, confounder, glucofm, dual_sensor, safety
    )
    return ScientificVisualizationArtifacts(
        output_dir=output,
        arena_radar_png=arena,
        confounder_cosine_png=confounder,
        glucofm_decomposition_png=glucofm,
        cgmacros_dualsensor_png=dual_sensor,
        fda_safety_timeline_png=safety,
        interactive_dashboard_html=dashboard,
    )


